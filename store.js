/* Content store: published content (data/content.js) + browser draft (IndexedDB),
   with undo/redo history and change notifications. */
(function (PF) {
  'use strict';
  const { stores, draftKey } = PF.config.storage;
  const CURRENT_VERSION = 1;

  let published = null;
  let state = null;
  let past = [];
  let future = [];
  let hasDraft = false;
  const events = PF.emitter();

  /** Schema migrations keyed by target version. Add entries when the content shape changes. */
  const migrations = {
    // 2: (c) => { ...; return c; }
  };

  function migrate(content) {
    let c = content;
    for (let v = (c.version || 1) + 1; v <= CURRENT_VERSION; v++) {
      if (migrations[v]) c = migrations[v](c);
      c.version = v;
    }
    return normalize(c);
  }

  /** Fill defaults from each section type so older/partial data still renders. */
  function normalize(content) {
    content.settings = content.settings || {};
    content.sections = (content.sections || []).map((s) => {
      const def = PF.sections[s.type];
      const base = def && def.defaults ? def.defaults() : {};
      return Object.assign({ visible: true, theme: 'dark', navLabel: '' }, base, s, { id: s.id || PF.uid(s.type || 'section') });
    });
    return content;
  }

  const persist = PF.debounce(() => {
    PF.db.put(stores.state, draftKey, state).catch(() => {});
    hasDraft = true;
  }, 300);

  const store = {
    async init(source) {
      published = migrate(PF.clone(source));
      const draft = await PF.db.get(stores.state, draftKey);
      hasDraft = !!draft;
      state = draft ? migrate(draft) : PF.clone(published);
      return state;
    },
    get: (path) => PF.getPath(state, path),
    get state() { return state; },
    get hasDraft() { return hasDraft; },
    on: events.on,

    /** Record a snapshot then mutate. opts.silent skips re-render (inline typing). */
    set(path, value, opts = {}) {
      if (!opts.merge) checkpoint();
      PF.setPath(state, path, value);
      persist();
      events.emit('change', { path, silent: !!opts.silent });
    },

    /** Structural edits (add/remove/move in arrays) via a mutator fn. */
    mutate(fn, opts = {}) {
      checkpoint();
      fn(state);
      persist();
      events.emit('change', { path: opts.path || '', structural: true });
    },

    replace(content) {
      checkpoint();
      state = migrate(PF.clone(content));
      persist();
      events.emit('change', { path: '', structural: true });
    },

    async discardDraft() {
      checkpoint();
      state = PF.clone(published);
      await PF.db.del(stores.state, draftKey);
      hasDraft = false;
      events.emit('change', { path: '', structural: true });
    },

    undo() { if (!past.length) return; future.push(PF.clone(state)); state = past.pop(); persist(); events.emit('change', { structural: true }); },
    redo() { if (!future.length) return; past.push(PF.clone(state)); state = future.pop(); persist(); events.emit('change', { structural: true }); },
    get canUndo() { return past.length > 0; },
    get canRedo() { return future.length > 0; },

    /** Serialized exports */
    async exportJSON() { return JSON.stringify(await PF.db.inlineMedia(state), null, 2); },
    async exportJS() {
      const json = await store.exportJSON();
      return `/* Generated by Admin mode — ${new Date().toISOString()} */\nwindow.PORTFOLIO_CONTENT = ${json};\n`;
    },
    parseImport(text) {
      const json = text.trim().replace(/^[\s\S]*?window\.PORTFOLIO_CONTENT\s*=\s*/, '').replace(/;\s*$/, '');
      const data = JSON.parse(json);
      if (!data || !Array.isArray(data.sections)) throw new Error('sections 배열이 없는 파일입니다.');
      return data;
    }
  };

  let lastCheckpoint = 0;
  function checkpoint() {
    // Coalesce rapid edits (typing) into one undo step.
    const now = Date.now();
    if (now - lastCheckpoint < 600 && past.length) { lastCheckpoint = now; return; }
    lastCheckpoint = now;
    past.push(PF.clone(state));
    if (past.length > PF.config.history.limit) past.shift();
    future = [];
  }

  PF.store = store;
})(window.PF);
